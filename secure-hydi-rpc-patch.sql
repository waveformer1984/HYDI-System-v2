-- 1. Read current health status (secure, anon accessible)
CREATE OR REPLACE FUNCTION read_current_health()
RETURNS TABLE (
    id BIGINT,
    run_timestamp TIMESTAMPTZ,
    current_status TEXT,
    trend_status TEXT,
    trend_reason TEXT,
    escalation_level TEXT,
    escalation_action TEXT,
    escalation_reason TEXT,
    jobs_queued INTEGER,
    jobs_failed INTEGER,
    jobs_dead INTEGER,
    avg_queue_size DECIMAL,
    critical_pct DECIMAL,
    warning_pct DECIMAL,
    events_last_hour INTEGER,
    auto_heals_24h INTEGER,
    last_check TIMESTAMPTZ,
    metadata JSONB,
    created_at TIMESTAMPTZ
)
SECURITY DEFINER
SET search_path = public
LANGUAGE sql
AS $$
    SELECT 
        id, run_timestamp, status, trend_status, trend_reason,
        escalation_level, escalation_action, escalation_reason,
        jobs_queued, jobs_failed, jobs_dead, avg_queue_size,
        critical_pct, warning_pct, events_last_hour, auto_heals_24h,
        last_check, metadata, created_at
    FROM system_health_runs
    WHERE run_timestamp = (
        SELECT MAX(run_timestamp) 
        FROM system_health_runs 
        WHERE run_timestamp >= NOW() - INTERVAL '24 hours'
    );
$$;

-- 2. Read health trends (secure, anon accessible)
CREATE OR REPLACE FUNCTION read_health_trends(limit_count INTEGER DEFAULT 20)
RETURNS TABLE (
    id BIGINT,
    run_timestamp TIMESTAMPTZ,
    status TEXT,
    trend_status TEXT,
    trend_reason TEXT,
    jobs_queued INTEGER,
    jobs_failed INTEGER,
    events_last_hour INTEGER,
    auto_heals_24h INTEGER
)
SECURITY DEFINER
SET search_path = public
LANGUAGE sql
AS $$
    SELECT 
        id, run_timestamp, status, trend_status, trend_reason,
        jobs_queued, jobs_failed, events_last_hour, auto_heals_24h
    FROM system_health_runs
    WHERE run_timestamp >= NOW() - INTERVAL '7 days'
    ORDER BY run_timestamp DESC
    LIMIT GREATEST(LEAST(limit_count, 100), 1);
$$;

-- 3. Read health metrics summary (secure, anon accessible)
CREATE OR REPLACE FUNCTION read_health_metrics()
RETURNS JSONB
SECURITY DEFINER
SET search_path = public
LANGUAGE sql
AS $$
    SELECT jsonb_build_object(
        'current_status', (
            SELECT status FROM read_current_health() 
            LIMIT 1
        ),
        'last_24h_stats', (
            SELECT jsonb_build_object(
                'total_runs', COUNT(*),
                'ok_runs', COUNT(*) FILTER (WHERE status = 'OK'),
                'warning_runs', COUNT(*) FILTER (WHERE status = 'WARNING'),
                'critical_runs', COUNT(*) FILTER (WHERE status = 'CRITICAL'),
                'avg_queue_size', ROUND(AVG(jobs_queued), 2),
                'total_events', SUM(events_last_hour),
                'total_heals', SUM(auto_heals_24h)
            )
            FROM system_health_runs
            WHERE run_timestamp >= NOW() - INTERVAL '24 hours'
        ),
        'trend_summary', (
            SELECT jsonb_build_object(
                'current_trend', trend_status,
                'trend_reason', trend_reason,
                'escalation_level', escalation_level
            )
            FROM read_current_health()
            LIMIT 1
        ),
        'last_updated', (
            SELECT MAX(last_check) 
            FROM system_health_runs 
            WHERE run_timestamp >= NOW() - INTERVAL '24 hours'
        )
    );
$$;

-- 4. Check system health (quick status check)
CREATE OR REPLACE FUNCTION check_system_health()
RETURNS JSONB
SECURITY DEFINER
SET search_path = public
LANGUAGE sql
AS $$
    SELECT jsonb_build_object(
        'status', COALESCE(current_status, 'UNKNOWN'),
        'trend', COALESCE(trend_status, 'unknown'),
        'escalation', COALESCE(escalation_level, 'OK'),
        'queue_size', COALESCE(jobs_queued, 0),
        'failed_jobs', COALESCE(jobs_failed, 0),
        'events_per_hour', COALESCE(events_last_hour, 0),
        'last_check', COALESCE(last_check, NOW()),
        'healthy', COALESCE(current_status, 'UNKNOWN') = 'OK'
    )
    FROM read_current_health()
    LIMIT 1;
$$;

-- 5. Get dashboard data (secure, anon accessible)
CREATE OR REPLACE FUNCTION get_dashboard_data()
RETURNS JSONB
SECURITY DEFINER
SET search_path = public
LANGUAGE sql
AS $$
    SELECT jsonb_build_object(
        'health', (
            SELECT row_to_json(d) FROM read_current_health() d LIMIT 1
        ),
        'metrics', read_health_metrics(),
        'trends', (
            SELECT jsonb_agg(
                jsonb_build_object(
                    'timestamp', run_timestamp,
                    'status', status,
                    'trend', trend_status,
                    'queue', jobs_queued,
                    'events', events_last_hour
                )
            )
            FROM read_health_trends(10)
        ),
        'timestamp', NOW()
    );
$$;

-- 6. PRIVILEGED: Insert health run (service role only)
CREATE OR REPLACE FUNCTION insert_health_run(
    p_status TEXT,
    p_trend_status TEXT DEFAULT NULL,
    p_trend_reason TEXT DEFAULT NULL,
    p_escalation_level TEXT DEFAULT NULL,
    p_escalation_action TEXT DEFAULT NULL,
    p_escalation_reason TEXT DEFAULT NULL,
    p_jobs_queued INTEGER DEFAULT 0,
    p_jobs_failed INTEGER DEFAULT 0,
    p_jobs_dead INTEGER DEFAULT 0,
    p_avg_queue_size DECIMAL DEFAULT NULL,
    p_critical_pct DECIMAL DEFAULT NULL,
    p_warning_pct DECIMAL DEFAULT NULL,
    p_events_last_hour INTEGER DEFAULT 0,
    p_auto_heals_24h INTEGER DEFAULT 0,
    p_metadata JSONB DEFAULT '{}'::jsonb
)
RETURNS BIGINT
SECURITY DEFINER
SET search_path = public
LANGUAGE plpgsql
AS $$
DECLARE
    new_id BIGINT;
BEGIN
    -- Service role check
    IF NOT pg_has_role('authenticated', 'service_role', 'member') THEN
        RAISE EXCEPTION 'insert_health_run requires service role';
    END IF;
    
    INSERT INTO system_health_runs (
        status, trend_status, trend_reason, escalation_level,
        escalation_action, escalation_reason, jobs_queued, jobs_failed,
        jobs_dead, avg_queue_size, critical_pct, warning_pct,
        events_last_hour, auto_heals_24h, metadata, last_check
    ) VALUES (
        p_status, p_trend_status, p_trend_reason, p_escalation_level,
        p_escalation_action, p_escalation_reason, p_jobs_queued, p_jobs_failed,
        p_jobs_dead, p_avg_queue_size, p_critical_pct, p_warning_pct,
        p_events_last_hour, p_auto_heals_24h, p_metadata, NOW()
    ) RETURNING id INTO new_id;
    
    RETURN new_id;
END;
$$;

-- 7. PRIVILEGED: Auto-heal from trends (service role only)
CREATE OR REPLACE FUNCTION auto_heal_from_trends()
RETURNS JSONB
SECURITY DEFINER
SET search_path = public
LANGUAGE plpgsql
AS $$
DECLARE
    current_status TEXT;
    trend_status TEXT;
    escalation_level TEXT;
    jobs_failed INTEGER;
    healed_count INTEGER := 0;
BEGIN
    -- Service role check
    IF NOT pg_has_role('authenticated', 'service_role', 'member') THEN
        RAISE EXCEPTION 'auto_heal_from_trends requires service role';
    END IF;
    
    -- Get current health
    SELECT status, trend_status, escalation_level, jobs_failed
    INTO current_status, trend_status, escalation_level, jobs_failed
    FROM read_current_health() LIMIT 1;
    
    -- Auto-heal logic
    IF current_status = 'CRITICAL' AND jobs_failed > 5 THEN
        -- Simulate healing actions
        UPDATE system_health_runs 
        SET jobs_failed = GREATEST(jobs_failed - 3, 0),
            auto_heals_24h = auto_heals_24h + 1,
            last_check = NOW()
        WHERE id = (SELECT id FROM read_current_health() LIMIT 1);
        
        healed_count := 3;
        
        -- Insert new health run showing improvement
        PERFORM insert_health_run(
            CASE WHEN jobs_failed <= 8 THEN 'WARNING' ELSE 'CRITICAL' END,
            'stable', 'Auto-heal actions taken',
            'OK', 'Auto-heal', 'Failed jobs cleared',
            jobs_failed - 3, 0, 0, NULL, NULL, NULL, 0, 1
        );
        
    ELSIF trend_status = 'critical_trend' THEN
        -- Trend-based healing
        PERFORM insert_health_run(
            'WARNING', 'degrading', 'Trend stabilization in progress',
            'WARNING', 'Monitoring', 'Critical trend detected',
            0, 0, 0, NULL, NULL, NULL, 0, 1
        );
        
        healed_count := 1;
    END IF;
    
    RETURN jsonb_build_object(
        'healed', healed_count,
        'previous_status', current_status,
        'trend', trend_status,
        'timestamp', NOW()
    );
END;
$$;

