#!/usr/bin/env node
/**
 * Simple HYDI Security Patch Application
 * Uses Supabase client to execute SQL patch
 */

require('dotenv').config();
const { createClient } = require('@supabase/supabase-js');
const fs = require('fs');
const path = require('path');

async function applyPatch() {
  console.log('🔧 HYDI Security Patch Application\n');
  
  // Check environment
  if (!process.env.SUPABASE_URL || !process.env.SUPABASE_SERVICE_ROLE_KEY) {
    console.error('❌ Missing environment variables');
    console.log('Required: SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY');
    process.exit(1);
  }
  
  // Create client
  const supabase = createClient(
    process.env.SUPABASE_URL,
    process.env.SUPABASE_SERVICE_ROLE_KEY
  );
  
  // Test connection
  try {
    const { data, error } = await supabase
      .from('information_schema.tables')
      .select('table_name')
      .limit(1);
    
    if (error) throw error;
    console.log('✅ Database connection verified');
  } catch (error) {
    console.error('❌ Database connection failed:', error.message);
    process.exit(1);
  }
  
  // Read and execute patch
  const sqlPath = path.join(__dirname, 'secure-hydi-rpc-patch.sql');
  const sqlPatch = fs.readFileSync(sqlPath, 'utf8');
  
  console.log('📄 Applying security patch...');
  
  // Execute using raw SQL - this requires admin access
  try {
    // First, create the base table if it doesn't exist
    console.log('📊 Creating system_health_runs table...');
    
    const { error: tableError } = await supabase.rpc('execute_sql', {
      sql: `
        CREATE TABLE IF NOT EXISTS system_health_runs (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            run_timestamp TIMESTAMPTZ DEFAULT NOW(),
            status TEXT NOT NULL CHECK (status IN ('OK', 'WARNING', 'CRITICAL', 'UNKNOWN')),
            trend_status TEXT CHECK (trend_status IN ('stable', 'degrading', 'critical_trend', 'unknown')),
            trend_reason TEXT,
            escalation_level TEXT CHECK (escalation_level IN ('OK', 'WARNING', 'CRITICAL')),
            escalation_action TEXT,
            escalation_reason TEXT,
            jobs_queued INTEGER DEFAULT 0,
            jobs_failed INTEGER DEFAULT 0,
            jobs_dead INTEGER DEFAULT 0,
            avg_queue_size DECIMAL(10,2),
            critical_pct DECIMAL(5,2),
            warning_pct DECIMAL(5,2),
            events_last_hour INTEGER DEFAULT 0,
            auto_heals_24h INTEGER DEFAULT 0,
            last_check TIMESTAMPTZ DEFAULT NOW(),
            metadata JSONB DEFAULT '{}'::jsonb,
            created_at TIMESTAMPTZ DEFAULT NOW()
        );
      `
    });
    
    if (tableError && !tableError.message?.includes('already exists')) {
      console.log('⚠️  Table creation issue:', tableError.message);
    }
    
    // Create secure functions one by one
    console.log('🔐 Creating secure RPC functions...');
    
    // 1. read_current_health
    const { error: func1Error } = await supabase.rpc('execute_sql', {
      sql: `
        CREATE OR REPLACE FUNCTION read_current_health()
        RETURNS TABLE (
            id BIGINT, run_timestamp TIMESTAMPTZ, current_status TEXT,
            trend_status TEXT, trend_reason TEXT, escalation_level TEXT,
            escalation_action TEXT, escalation_reason TEXT, jobs_queued INTEGER,
            jobs_failed INTEGER, jobs_dead INTEGER, avg_queue_size DECIMAL,
            critical_pct DECIMAL, warning_pct DECIMAL, events_last_hour INTEGER,
            auto_heals_24h INTEGER, last_check TIMESTAMPTZ, metadata JSONB, created_at TIMESTAMPTZ
        )
        SECURITY DEFINER
        SET search_path = public
        LANGUAGE sql
        AS $$
            SELECT 
                id, run_timestamp, status, trend_status, trend_reason,
                escalation_level, escalation_action, escalation_reason,
                jobs_queued, jobs_failed, jobs_dead, avg_queue_size,
                critical_pct, warning_pct, events_last_hour, auto_heals_24h,
                last_check, metadata, created_at
            FROM system_health_runs
            WHERE run_timestamp = (
                SELECT MAX(run_timestamp) 
                FROM system_health_runs 
                WHERE run_timestamp >= NOW() - INTERVAL '24 hours'
            );
        $$;
      `
    });
    
    if (func1Error) {
      console.log('❌ read_current_health failed:', func1Error.message);
    } else {
      console.log('✅ read_current_health created');
    }
    
    // 2. check_system_health
    const { error: func2Error } = await supabase.rpc('execute_sql', {
      sql: `
        CREATE OR REPLACE FUNCTION check_system_health()
        RETURNS JSONB
        SECURITY DEFINER
        SET search_path = public
        LANGUAGE sql
        AS $$
            SELECT jsonb_build_object(
                'status', COALESCE(current_status, 'UNKNOWN'),
                'trend', COALESCE(trend_status, 'unknown'),
                'escalation', COALESCE(escalation_level, 'OK'),
                'queue_size', COALESCE(jobs_queued, 0),
                'failed_jobs', COALESCE(jobs_failed, 0),
                'events_per_hour', COALESCE(events_last_hour, 0),
                'last_check', COALESCE(last_check, NOW()),
                'healthy', COALESCE(current_status, 'UNKNOWN') = 'OK'
            )
            FROM read_current_health()
            LIMIT 1;
        $$;
      `
    });
    
    if (func2Error) {
      console.log('❌ check_system_health failed:', func2Error.message);
    } else {
      console.log('✅ check_system_health created');
    }
    
    // 3. get_dashboard_data
    const { error: func3Error } = await supabase.rpc('execute_sql', {
      sql: `
        CREATE OR REPLACE FUNCTION get_dashboard_data()
        RETURNS JSONB
        SECURITY DEFINER
        SET search_path = public
        LANGUAGE sql
        AS $$
            SELECT jsonb_build_object(
                'health', (
                    SELECT row_to_json(d) FROM read_current_health() d LIMIT 1
                ),
                'timestamp', NOW()
            );
        $$;
      `
    });
    
    if (func3Error) {
      console.log('❌ get_dashboard_data failed:', func3Error.message);
    } else {
      console.log('✅ get_dashboard_data created');
    }
    
    // Grant permissions
    console.log('🔑 Setting permissions...');
    
    const { error: permError } = await supabase.rpc('execute_sql', {
      sql: `
        GRANT EXECUTE ON FUNCTION read_current_health() TO anon, authenticated;
        GRANT EXECUTE ON FUNCTION check_system_health() TO anon, authenticated;
        GRANT EXECUTE ON FUNCTION get_dashboard_data() TO anon, authenticated;
      `
    });
    
    if (permError) {
      console.log('⚠️  Permission setup issue:', permError.message);
    } else {
      console.log('✅ Permissions granted');
    }
    
    // Insert initial data
    console.log('📊 Inserting initial health data...');
    
    const { error: insertError } = await supabase
      .from('system_health_runs')
      .upsert([{
        status: 'OK',
        trend_status: 'stable',
        trend_reason: 'System initialized with security patch',
        escalation_level: 'OK',
        jobs_queued: 0,
        jobs_failed: 0,
        events_last_hour: 0,
        auto_heals_24h: 0
      }], { onConflict: 'status' });
    
    if (insertError && !insertError.message?.includes('duplicate')) {
      console.log('⚠️  Initial data issue:', insertError.message);
    } else {
      console.log('✅ Initial health data created');
    }
    
    console.log('\n🎉 Security patch applied successfully!');
    console.log('\n📋 Available secure functions:');
    console.log('   • read_current_health() - Full health record');
    console.log('   • check_system_health() - Quick status check');
    console.log('   • get_dashboard_data() - Dashboard JSON');
    
    console.log('\n🧪 Testing functions...');
    
    // Test the functions
    try {
      const { data: healthCheck, error: testError } = await supabase
        .rpc('check_system_health');
      
      if (testError) {
        console.log('❌ Function test failed:', testError.message);
      } else {
        console.log('✅ check_system_health() working:', healthCheck.status);
      }
    } catch (error) {
      console.log('❌ Test failed:', error.message);
    }
    
  } catch (error) {
    console.error('❌ Patch application failed:', error.message);
    console.log('\n💡 Alternative: Apply patch manually in Supabase Dashboard');
    console.log('1. Go to Supabase Dashboard > SQL Editor');
    console.log('2. Copy contents of secure-hydi-rpc-patch.sql');
    console.log('3. Execute the SQL');
    process.exit(1);
  }
}

// Run it
applyPatch()
  .then(() => {
    console.log('\n✨ Security patch complete');
    process.exit(0);
  })
  .catch((error) => {
    console.error('\n💥 Patch failed:', error);
    process.exit(1);
  });
