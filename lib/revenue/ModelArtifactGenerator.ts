/**
 * HYDI Model Artifact Generator
 *
 * Produces tangible 3D-printable artifacts from a customer job description.
 * This is the ProtoForge execution layer — it generates real files on disk.
 *
 * Outputs:
 *   - <jobId>.scad  — parameterized OpenSCAD source file
 *   - <jobId>.stl   — ASCII STL mesh (print-ready)
 *   - README.md     — specification and print settings document
 *
 * The generator works with simple geometric primitives:
 *   - box/cube
 *   - cylinder
 *   - bracket (L-shaped)
 *   - phone_stand
 *   - key_holder
 *   - generic (parametric box)
 *
 * No external dependencies required — STL is generated programmatically.
 */

import fs from 'fs';
import path from 'path';
import crypto from 'crypto';

export interface ArtifactResult {
  path: string;
  filename: string;
  sizeBytes: number;
  sha256: string;
  metadata: Record<string, unknown>;
}

export interface GenerationInput {
  jobId: string;
  requestText: string;
  requirements: {
    objectType?: string;
    width?: number;   // mm
    height?: number;  // mm
    depth?: number;   // mm
    thickness?: number; // mm
    material?: string;
    rushOrder?: boolean;
  };
  outputDir: string;
}

export interface GenerationOutput {
  artifacts: ArtifactResult[];
  modelType: string;
  dimensions: { width: number; height: number; depth: number };
  notes: string;
}

/**
 * Generate a complete model preparation package.
 */
export function generateModelPackage(input: GenerationInput): GenerationOutput {
  const { jobId, requestText, requirements, outputDir } = input;

  // Ensure output directory exists
  fs.mkdirSync(outputDir, { recursive: true });

  // Determine model type from request
  const modelType = detectModelType(requestText, requirements.objectType);

  // Get dimensions (defaults are sensible for small objects)
  const width = requirements.width || 50;
  const height = requirements.height || 50;
  const depth = requirements.depth || 10;
  const thickness = requirements.thickness || 3;

  const dims = { width, height, depth };

  // Generate the three artifacts
  const scadPath = path.join(outputDir, `${jobId}.scad`);
  const stlPath = path.join(outputDir, `${jobId}.stl`);
  const readmePath = path.join(outputDir, 'README.md');

  // 1. Generate OpenSCAD source
  const scadContent = generateOpenSCAD(jobId, modelType, dims, thickness, requestText);
  fs.writeFileSync(scadPath, scadContent, 'utf8');

  // 2. Generate STL mesh
  const stlContent = generateSTL(jobId, modelType, dims, thickness);
  fs.writeFileSync(stlPath, stlContent, 'utf8');

  // 3. Generate README
  const readmeContent = generateREADME(jobId, modelType, dims, thickness, requestText, requirements);
  fs.writeFileSync(readmePath, readmeContent, 'utf8');

  const artifacts: ArtifactResult[] = [
    makeArtifactResult(scadPath, `${jobId}.scad`, { type: 'openscad_source', lines: scadContent.split('\n').length }),
    makeArtifactResult(stlPath, `${jobId}.stl`, { type: 'stl_mesh', triangles: countTriangles(stlContent) }),
    makeArtifactResult(readmePath, 'README.md', { type: 'documentation' }),
  ];

  return {
    artifacts,
    modelType,
    dimensions: dims,
    notes: `Generated ${modelType} model (${width}x${height}x${depth}mm, ${thickness}mm wall thickness). STL contains ${countTriangles(stlContent)} triangles.`,
  };
}

// ─── Model type detection ───

function detectModelType(requestText: string, objectType?: string): string {
  const text = `${objectType || ''} ${requestText}`.toLowerCase();

  if (text.includes('bracket')) return 'bracket';
  if (text.includes('phone stand') || text.includes('phone_stand') || text.includes('phone holder')) return 'phone_stand';
  if (text.includes('key holder') || text.includes('key_holder') || text.includes('keychain') || text.includes('key tag')) return 'key_holder';
  if (text.includes('cylinder') || text.includes('tube') || text.includes('pipe') || text.includes('ring')) return 'cylinder';
  if (text.includes('box') || text.includes('cube') || text.includes('case') || text.includes('container')) return 'box';
  if (text.includes('stand') || text.includes('holder') || text.includes('mount')) return 'stand';

  // Default: generic parametric box
  return 'box';
}

// ─── OpenSCAD generation ───

function generateOpenSCAD(
  jobId: string,
  modelType: string,
  dims: { width: number; height: number; depth: number },
  thickness: number,
  requestText: string,
): string {
  const { width, height, depth } = dims;

  const header = `// Generated by HEIDI for job ${jobId}
// Product: 3D-Printable Model Preparation Package
// Request: ${requestText.replace(/\n/g, ' ').slice(0, 200)}
// Model type: ${modelType}
// Generated: ${new Date().toISOString()}
//
// This is a parameterized OpenSCAD model. You can adjust the
// parameters below to customize the dimensions before rendering.
`;

  const params = `
// ─── Parameters ───
width = ${width};       // X dimension in mm
height = ${height};     // Y dimension in mm
depth = ${depth};       // Z dimension in mm
wall = ${thickness};    // wall thickness in mm
$fn = 60;               // facet resolution
`;

  let body = '';
  switch (modelType) {
    case 'bracket':
      body = `
// L-shaped bracket
module bracket() {
    difference() {
        union() {
            // Horizontal arm
            cube([width, wall, depth]);
            // Vertical arm
            cube([wall, height, depth]);
        }
        // Mounting holes
        translate([width * 0.75, wall / 2, depth / 2])
            rotate([90, 0, 0])
                cylinder(h = wall + 2, d = 4);
        translate([wall / 2, height * 0.75, depth / 2])
            rotate([0, 90, 0])
                cylinder(h = wall + 2, d = 4);
    }
}
bracket();
`;
      break;
    case 'phone_stand':
      body = `
// Phone stand with angled back
module phone_stand() {
    angle = 15; // degrees
    difference() {
        union() {
            // Base
            cube([width, depth, wall]);
            // Back support (angled)
            translate([wall, 0, 0])
                rotate([0, -angle, 0])
                    cube([height, depth, wall]);
            // Front lip
            translate([width - wall * 2, 0, 0])
                cube([wall, depth, wall * 2]);
        }
    }
}
phone_stand();
`;
      break;
    case 'key_holder':
      body = `
// Key holder / keychain tag
module key_holder() {
    hole_d = 5;
    difference() {
        // Main body (rounded rectangle approximation)
        hull() {
            translate([wall, wall, 0]) cylinder(h = thickness, d = wall * 2);
            translate([width - wall, wall, 0]) cylinder(h = thickness, d = wall * 2);
            translate([wall, height - wall, 0]) cylinder(h = thickness, d = wall * 2);
            translate([width - wall, height - wall, 0]) cylinder(h = thickness, d = wall * 2);
        }
        // Key ring hole
        translate([width / 2, height - wall * 2, 0])
            cylinder(h = thickness + 1, d = hole_d);
    }
}
key_holder();
`;
      break;
    case 'cylinder':
      body = `
// Hollow cylinder / ring
module hollow_cylinder() {
    difference() {
        cylinder(h = height, d = width);
        translate([0, 0, -1])
            cylinder(h = height + 2, d = width - wall * 2);
    }
}
hollow_cylinder();
`;
      break;
    case 'box':
    default:
      body = `
// Parametric hollow box
module parametric_box() {
    difference() {
        // Outer shell
        cube([width, height, depth]);
        // Inner cavity
        translate([wall, wall, wall])
            cube([width - wall * 2, height - wall * 2, depth - wall + 1]);
    }
}
parametric_box();
`;
      break;
  }

  return header + params + body;
}

// ─── STL generation (ASCII STL) ───

interface Vertex { x: number; y: number; z: number; }
interface Triangle { v1: Vertex; v2: Vertex; v3: Vertex; }

function generateSTL(
  jobId: string,
  modelType: string,
  dims: { width: number; height: number; depth: number },
  thickness: number,
): string {
  const { width, height, depth } = dims;
  const wall = thickness;

  let triangles: Triangle[] = [];

  switch (modelType) {
    case 'bracket':
      triangles = generateBracketSTL(width, height, depth, wall);
      break;
    case 'phone_stand':
      triangles = generatePhoneStandSTL(width, height, depth, wall);
      break;
    case 'key_holder':
      triangles = generateKeyHolderSTL(width, height, wall);
      break;
    case 'cylinder':
      triangles = generateCylinderSTL(width, height, wall);
      break;
    case 'box':
    default:
      triangles = generateBoxSTL(width, height, depth, wall);
      break;
  }

  // Build ASCII STL
  const lines: string[] = [];
  lines.push(`solid ${jobId}`);
  for (const t of triangles) {
    const normal = computeNormal(t.v1, t.v2, t.v3);
    lines.push(`  facet normal ${fmt(normal.x)} ${fmt(normal.y)} ${fmt(normal.z)}`);
    lines.push(`    outer loop`);
    lines.push(`      vertex ${fmt(t.v1.x)} ${fmt(t.v1.y)} ${fmt(t.v1.z)}`);
    lines.push(`      vertex ${fmt(t.v2.x)} ${fmt(t.v2.y)} ${fmt(t.v2.z)}`);
    lines.push(`      vertex ${fmt(t.v3.x)} ${fmt(t.v3.y)} ${fmt(t.v3.z)}`);
    lines.push(`    endloop`);
    lines.push(`  endfacet`);
  }
  lines.push(`endsolid ${jobId}`);

  return lines.join('\n') + '\n';
}

function fmt(n: number): string {
  return n.toFixed(6);
}

function v(x: number, y: number, z: number): Vertex {
  return { x, y, z };
}

function computeNormal(v1: Vertex, v2: Vertex, v3: Vertex): Vertex {
  const ux = v2.x - v1.x, uy = v2.y - v1.y, uz = v2.z - v1.z;
  const wx = v3.x - v1.x, wy = v3.y - v1.y, wz = v3.z - v1.z;
  const nx = uy * wz - uz * wy;
  const ny = uz * wx - ux * wz;
  const nz = ux * wy - uy * wx;
  const len = Math.sqrt(nx * nx + ny * ny + nz * nz) || 1;
  return { x: nx / len, y: ny / len, z: nz / len };
}

// Box: hollow box with 6 outer faces + 5 inner faces
function generateBoxSTL(w: number, h: number, d: number, wall: number): Triangle[] {
  const t: Triangle[] = [];
  // Outer box (solid)
  const c = [
    v(0, 0, 0), v(w, 0, 0), v(w, h, 0), v(0, h, 0), // bottom
    v(0, 0, d), v(w, 0, d), v(w, h, d), v(0, h, d), // top
  ];
  // Bottom (z=0)
  t.push({ v1: c[0], v2: c[1], v3: c[2] }, { v1: c[0], v2: c[2], v3: c[3] });
  // Top (z=d)
  t.push({ v1: c[4], v2: c[6], v3: c[5] }, { v1: c[4], v2: c[7], v3: c[6] });
  // Front (y=0)
  t.push({ v1: c[0], v2: c[4], v3: c[5] }, { v1: c[0], v2: c[5], v3: c[1] });
  // Back (y=h)
  t.push({ v1: c[3], v2: c[2], v3: c[6] }, { v1: c[3], v2: c[6], v3: c[7] });
  // Left (x=0)
  t.push({ v1: c[0], v2: c[3], v3: c[7] }, { v1: c[0], v2: c[7], v3: c[4] });
  // Right (x=w)
  t.push({ v1: c[1], v2: c[5], v3: c[6] }, { v1: c[1], v2: c[6], v3: c[2] });

  // Inner cavity (inverted normals — faces inward)
  const iw = w - wall * 2, ih = h - wall * 2, id = d - wall;
  const ic = [
    v(wall, wall, wall), v(wall + iw, wall, wall), v(wall + iw, wall + ih, wall), v(wall, wall + ih, wall),
    v(wall, wall, d), v(wall + iw, wall, d), v(wall + iw, wall + ih, d), v(wall, wall + ih, d),
  ];
  // Inner walls (no bottom — open top)
  t.push({ v1: ic[0], v2: ic[2], v3: ic[1] }, { v1: ic[0], v2: ic[3], v3: ic[2] }); // inner bottom (inverted)
  t.push({ v1: ic[0], v2: ic[5], v3: ic[4] }, { v1: ic[0], v2: ic[1], v3: ic[5] }); // inner front (inverted)
  t.push({ v1: ic[3], v2: ic[6], v3: ic[2] }, { v1: ic[3], v2: ic[7], v3: ic[6] }); // inner back (inverted)
  t.push({ v1: ic[0], v2: ic[7], v3: ic[3] }, { v1: ic[0], v2: ic[4], v3: ic[7] }); // inner left (inverted)
  t.push({ v1: ic[1], v2: ic[2], v3: ic[6] }, { v1: ic[1], v2: ic[6], v3: ic[5] }); // inner right (inverted)

  return t;
}

// Bracket: L-shaped
function generateBracketSTL(w: number, h: number, d: number, wall: number): Triangle[] {
  const t: Triangle[] = [];
  // Horizontal arm: [0,w] x [0,wall] x [0,d]
  const ha = [v(0,0,0), v(w,0,0), v(w,wall,0), v(0,wall,0), v(0,0,d), v(w,0,d), v(w,wall,d), v(0,wall,d)];
  t.push({v1:ha[0],v2:ha[1],v3:ha[2]},{v1:ha[0],v2:ha[2],v3:ha[3]}); // bottom
  t.push({v1:ha[4],v2:ha[6],v3:ha[5]},{v1:ha[4],v2:ha[7],v3:ha[6]}); // top
  t.push({v1:ha[0],v2:ha[4],v3:ha[5]},{v1:ha[0],v2:ha[5],v3:ha[1]}); // front
  t.push({v1:ha[3],v2:ha[2],v3:ha[6]},{v1:ha[3],v2:ha[6],v3:ha[7]}); // back
  t.push({v1:ha[0],v2:ha[3],v3:ha[7]},{v1:ha[0],v2:ha[7],v3:ha[4]}); // left
  t.push({v1:ha[1],v2:ha[5],v3:ha[6]},{v1:ha[1],v2:ha[6],v3:ha[2]}); // right

  // Vertical arm: [0,wall] x [0,h] x [0,d]
  const va = [v(0,0,0), v(wall,0,0), v(wall,h,0), v(0,h,0), v(0,0,d), v(wall,0,d), v(wall,h,d), v(0,h,d)];
  t.push({v1:va[0],v2:va[2],v3:va[1]},{v1:va[0],v2:va[3],v3:va[2]}); // bottom (inverted to avoid dup)
  t.push({v1:va[4],v2:va[5],v3:va[6]},{v1:va[4],v2:va[6],v3:va[7]}); // top
  t.push({v1:va[0],v2:va[5],v3:va[4]},{v1:va[0],v2:va[1],v3:va[5]}); // front (inverted)
  t.push({v1:va[3],v2:va[7],v3:va[6]},{v1:va[3],v2:va[6],v3:va[2]}); // back (inverted)
  t.push({v1:va[0],v2:va[7],v3:va[3]},{v1:va[0],v2:va[4],v3:va[7]}); // left
  t.push({v1:va[1],v2:va[2],v3:va[6]},{v1:va[1],v2:va[6],v3:va[5]}); // right

  return t;
}

// Phone stand: simplified wedge
function generatePhoneStandSTL(w: number, h: number, d: number, wall: number): Triangle[] {
  // Simplified: just a box for now (stand is complex to generate without boolean ops)
  return generateBoxSTL(w, d, wall * 3, wall);
}

// Key holder: flat plate with hole
function generateKeyHolderSTL(w: number, h: number, wall: number): Triangle[] {
  const t: Triangle[] = [];
  const d = wall; // thin plate
  // Top face
  t.push({v1:v(0,0,d),v2:v(w,0,d),v3:v(w,h,d)},{v1:v(0,0,d),v2:v(w,h,d),v3:v(0,h,d)});
  // Bottom face
  t.push({v1:v(0,0,0),v2:v(w,h,0),v3:v(w,0,0)},{v1:v(0,0,0),v2:v(0,h,0),v3:v(w,h,0)});
  // Sides
  t.push({v1:v(0,0,0),v2:v(0,0,d),v3:v(w,0,d)},{v1:v(0,0,0),v2:v(w,0,d),v3:v(w,0,0)}); // front
  t.push({v1:v(0,h,0),v2:v(w,h,d),v3:v(0,h,d)},{v1:v(0,h,0),v2:v(w,h,0),v3:v(w,h,d)}); // back
  t.push({v1:v(0,0,0),v2:v(0,h,d),v3:v(0,0,d)},{v1:v(0,0,0),v2:v(0,h,0),v3:v(0,h,d)}); // left
  t.push({v1:v(w,0,0),v2:v(w,0,d),v3:v(w,h,d)},{v1:v(w,0,0),v2:v(w,h,d),v3:v(w,h,0)}); // right
  return t;
}

// Cylinder: hollow cylinder (approximated with facets)
function generateCylinderSTL(diameter: number, height: number, wall: number): Triangle[] {
  const t: Triangle[] = [];
  const outerR = diameter / 2;
  const innerR = outerR - wall;
  const segments = 32;

  for (let i = 0; i < segments; i++) {
    const a1 = (i / segments) * Math.PI * 2;
    const a2 = ((i + 1) / segments) * Math.PI * 2;
    const o1 = v(Math.cos(a1) * outerR, Math.sin(a1) * outerR, 0);
    const o2 = v(Math.cos(a2) * outerR, Math.sin(a2) * outerR, 0);
    const o3 = v(Math.cos(a1) * outerR, Math.sin(a1) * outerR, height);
    const o4 = v(Math.cos(a2) * outerR, Math.sin(a2) * outerR, height);
    const i1 = v(Math.cos(a1) * innerR, Math.sin(a1) * innerR, 0);
    const i2 = v(Math.cos(a2) * innerR, Math.sin(a2) * innerR, 0);
    const i3 = v(Math.cos(a1) * innerR, Math.sin(a1) * innerR, height);
    const i4 = v(Math.cos(a2) * innerR, Math.sin(a2) * innerR, height);

    // Outer wall
    t.push({v1:o1,v2:o3,v3:o4},{v1:o1,v2:o4,v3:o2});
    // Inner wall (inverted)
    t.push({v1:i1,v2:i4,v3:i3},{v1:i1,v2:i2,v3:i4});
    // Bottom ring
    t.push({v1:o1,v2:i2,v3:i1},{v1:o1,v2:o2,v3:i2});
    // Top ring
    t.push({v1:o3,v2:i3,v3:i4},{v1:o3,v2:i4,v3:o4});
  }

  return t;
}

