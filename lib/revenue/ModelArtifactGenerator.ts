// ─── Helpers ───

function makeArtifactResult(filePath: string, filename: string, metadata: Record<string, unknown>): ArtifactResult {
  const content = fs.readFileSync(filePath);
  const hash = crypto.createHash('sha256').update(content).digest('hex');
  return {
    path: filePath,
    filename,
    sizeBytes: content.length,
    sha256: hash,
    metadata,
  };
}

function countTriangles(stlContent: string): number {
  return (stlContent.match(/endfacet/g) || []).length;
}

/**
 * Verify that an artifact set is complete and valid.
 */
export function verifyArtifacts(artifacts: ArtifactResult[]): { verified: boolean; details: string } {
  if (artifacts.length < 3) {
    return { verified: false, details: `Expected 3 artifacts, got ${artifacts.length}` };
  }

  const hasScad = artifacts.some(a => a.filename.endsWith('.scad'));
  const hasStl = artifacts.some(a => a.filename.endsWith('.stl'));
  const hasReadme = artifacts.some(a => a.filename === 'README.md');

  if (!hasScad) return { verified: false, details: 'Missing .scad file' };
  if (!hasStl) return { verified: false, details: 'Missing .stl file' };
  if (!hasReadme) return { verified: false, details: 'Missing README.md' };

  // Verify STL has content
  const stl = artifacts.find(a => a.filename.endsWith('.stl'))!;
  if (stl.sizeBytes < 100) {
    return { verified: false, details: `STL file too small (${stl.sizeBytes} bytes)` };
  }

  const triangles = stl.metadata.triangles as number;
  if (!triangles || triangles < 4) {
    return { verified: false, details: `STL has insufficient triangles (${triangles})` };
  }

  return { verified: true, details: `3 artifacts verified: .scad + .stl (${triangles} triangles) + README.md` };
}
